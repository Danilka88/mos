/**
 * Генерирует массив годовых финансовых данных для одной компании.
 * Симулирует реалистичный, но случайный рост показателей, а также
 * добавляет преднамеренные аномалии для конкретных компаний для демонстрационных целей.
 * @param startYear - Начальный год для генерации данных.
 * @param endYear - Конечный год.
 * @param baseRevenue - Базовое значение выручки для первой точки.
 * @param baseProfit - Базовое значение прибыли.
 * @param baseEmployees - Базовая численность сотрудников.
 * @param companyName - Имя компании для создания специфичных аномалий.
 * @returns Массив объектов YearlyData.
 */
const generateYearlyData = (startYear: number, endYear: number, baseRevenue: number, baseProfit: number, baseEmployees: number, companyName: string): YearlyData[] => {
    const data: YearlyData[] = [];
    for (let year = startYear; year <= endYear; year++) {
        // Случайный фактор роста от -5% до +15% для внесения вариативности
        const growthFactor = 1 + (Math.random() * 0.2 - 0.05);

        // Моделируем рост показателей со временем
        let revenue = Math.round((baseRevenue * growthFactor) * (1 + (year - startYear) * (Math.random() * 0.1 + 0.05)));
        let profit = Math.round((baseProfit * growthFactor) * (1 + (year - startYear) * (Math.random() * 0.15 + 0.03)));
        let employees = Math.round((baseEmployees * (1 + (Math.random() * 0.05 - 0.02))) * (1 + (year - startYear) * 0.02));

        // =================================================================
        // --- ИСКУССТВЕННЫЕ АНОМАЛИИ ДЛЯ ДЕМОНСТРАЦИИ РАБОТЫ ИИ ---
        // Цель: Показать, как ИИ может выявлять нетипичные события.
        // =================================================================

        // 1. Взрывной рост "Москвича" после перезапуска.
        // Показывает способность ИИ находить позитивные "черные лебеди".
        if (year >= 2024 && companyName.includes("Москвич")) {
             revenue *= 2.5;
             profit *= 1.5;
             employees *= 1.8;
        }
        // 2. Падение прибыли "Красного Октября" из-за внешних факторов (симуляция роста цен на сырье).
        // Показывает способность ИИ находить негативные события и связывать их с контекстом (в промпте).
        if (year === 2025 && companyName.includes("КРАСНЫЙ ОКТЯБРЬ")) {
            profit = Math.round(profit * 0.4); 
        }
        // 3. Резкий рост показателей "Микрона" на фоне импортозамещения (симуляция получения гос. заказов).
        // Показывает способность ИИ выявлять лидеров роста.
        if (year === 2024 && companyName.includes("Микрон")) {
            profit = Math.round(profit * 1.8);
            revenue = Math.round(revenue * 1.5);
        }

        // Расчет производных показателей для большей реалистичности данных
        const payroll = Math.round(employees * (90 + Math.random() * 40) * 12); // Средняя з/п 90-130 тыс. в месяц
        const personalIncomeTax = Math.round(payroll * 0.13); // НДФЛ
        const profitTax = Math.round(profit > 0 ? profit * 0.2 : 0); // Налог на прибыль (20%)
        const propertyTax = Math.round(revenue * 0.01); // Налог на имущество (условно 1% от выручки)
        const taxes = personalIncomeTax + profitTax + propertyTax;

        data.push({
            year,
            revenue,
            profit,
            employees,
            taxes,
            payroll,
            profitTax,
            propertyTax,
            personalIncomeTax
        });
    }
    return data;
}

