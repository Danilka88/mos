/**
 * Асинхронный генератор для имитации потоковой передачи текста (streaming).
 * @param text - Полный текст для "стриминга".
 * @param chunkSize - Размер одного фрагмента текста.
 * @param delay - Задержка между фрагментами в мс.
 */
async function* streamText(text: string, chunkSize = 5, delay = 20): AsyncIterable<{ text: string }> {
    for (let i = 0; i < text.length; i += chunkSize) {
        const chunk = text.slice(i, i + chunkSize);
        yield { text: chunk };
        await new Promise(resolve => setTimeout(resolve, delay));
    }
}

/**
 * Имитирует получение полного ответа от модели (для генерации списков инсайтов).
 * Используется ИИ-Агентами #1 и #2.
 * @param prompt - Текст запроса (промпта), на основе которого подбирается моковый ответ.
 */
export async function generateInsight(prompt: string): Promise<string> {
    await new Promise(resolve => setTimeout(resolve, Math.random() * 400 + 100)); // Имитация задержки сети
    if (prompt.includes("НА УРОВНЕ ОТРАСЛЕЙ")) {
        if (prompt.includes("САМЫХ КРИТИЧНЫХ")) return mockIndustryInsights.critical;
        if (prompt.includes("САМЫХ ПОЗИТИВНЫХ")) return mockIndustryInsights.positive;
        if (prompt.includes("потенциальных РИСКОВ")) return mockIndustryInsights.warning;
        if (prompt.includes("ИНТЕРЕСНЫХ СРАВНЕНИЙ")) return mockIndustryInsights.info;
    } else {
        if (prompt.includes("САМЫХ КРИТИЧНЫХ")) return mockCompanyInsights.critical;
        if (prompt.includes("САМЫХ ПОЗИТИВНЫХ")) return mockCompanyInsights.positive;
        if (prompt.includes("потенциальных РИСКОВ")) return mockCompanyInsights.warning;
        if (prompt.includes("ИНТЕРЕСНЫХ, не очевидных наблюдений")) return mockCompanyInsights.info;
    }
    return "[]"; // Возвращаем пустой массив, если промпт не подошел
}

/**
 * Имитирует генерацию инсайта в потоковом режиме (для модальных окон).
 * @param prompt - Текст запроса (промпта) для подбора детального ответа.
 */
export async function generateInsightStream(prompt: string): Promise<AsyncIterable<{ text: string }>> {
    await new Promise(resolve => setTimeout(resolve, 200));
    let responseText = "Анализ для данного запроса не найден в базе моковых данных.";
    if (prompt.includes("Раскрой подробнее следующий вывод")) {
        const key = Object.keys(mockDetails).find(k => prompt.includes(`'${k}'`));
        if (key) responseText = mockDetails[key];
    } else if (prompt.includes("Проанализируй эти агрегированные данные")) {
        if (prompt.includes("'общая выручка'")) responseText = mockDetails["общая выручка"];
        else if (prompt.includes("'общая чистая прибыль'")) responseText = mockDetails["общая чистая прибыль"];
        else if (prompt.includes("'средняя зарплата'")) responseText = mockDetails["средняя зарплата"];
    }
    return streamText(responseText);
}

/**
 * =================================================================================
 * ИИ-АГЕНТ #3: Анализ ОДНОЙ КОНКРЕТНОЙ компании.
 * Имитирует получение инсайтов для страницы детализации компании.
 * @param company - Полные данные по компании для анализа.
 * @returns Промис, который разрешается объектом с инсайтами по 4 категориям.
 * =================================================================================
 */
export async function fetchSingleCompanyInsights(company: CompanyData): Promise<{ [key in InsightType]: string[] }> {
    await new Promise(resolve => setTimeout(resolve, 800)); // Имитация задержки сети

    const latestFin = company.financials[company.financials.length - 1];
    const prevFin = company.financials[company.financials.length - 2];
    const revenueGrowth = prevFin ? (latestFin.revenue - prevFin.revenue) / prevFin.revenue : 0;
    const profitGrowth = prevFin ? (latestFin.profit - prevFin.profit) / prevFin.profit : 0;

    const insights: { [key in InsightType]: string[] } = {
        critical: [],
        warning: [],
        positive: [],
        info: [`Рентабельность по чистой прибыли в ${latestFin.year} году составила ${((latestFin.profit / latestFin.revenue) * 100).toFixed(1)}%.`, `Средняя выработка на сотрудника: ${(latestFin.revenue / latestFin.employees).toFixed(0)} тыс. руб.`]
    };

    if (latestFin.profit < 0) insights.critical.push(`Компания зафиксировала чистый убыток в размере ${Math.abs(latestFin.profit)} тыс. руб. в ${latestFin.year} году.`);
    if (profitGrowth < -0.2) insights.critical.push(`Резкое падение прибыли на ${Math.abs(profitGrowth * 100).toFixed(0)}% в ${latestFin.year} году.`);
    if (revenueGrowth < -0.1) insights.warning.push(`Зафиксировано снижение выручки на ${Math.abs(revenueGrowth * 100).toFixed(0)}% в ${latestFin.year} году.`);
    if (revenueGrowth > 0.25) insights.positive.push(`Значительный рост выручки на ${(revenueGrowth * 100).toFixed(0)}% в ${latestFin.year} году.`);
    else if (revenueGrowth > 0.1) insights.positive.push(`Уверенный рост выручки на ${(revenueGrowth * 100).toFixed(0)}% в ${latestFin.year} году.`);
    if (profitGrowth > 0.3) insights.positive.push(`Впечатляющий рост чистой прибыли на ${(profitGrowth * 100).toFixed(0)}% в ${latestFin.year} году.`);
    if (revenueGrowth > 0 && revenueGrowth < 0.03) insights.warning.push(`Темпы роста выручки замедлились до ${ (revenueGrowth * 100).toFixed(1)}%, что может сигнализировать о стагнации.`);
    
    if (company.name.includes('Москвич') && latestFin.year >= 2024) {
        insights.positive.push('Перезапуск производства привел к многократному росту выручки.');
        insights.warning.push('Несмотря на рост, компания все еще может быть операционно убыточной. Требуется анализ затрат.');
    }
    if (company.name.includes('Микрон')) {
        insights.positive.push('Компания является ключевым игроком в программе импортозамещения электроники.');
        insights.warning.push('Высокая зависимость от государственных субсидий и заказов.');
    }
     if (company.name.includes('КРАСНЫЙ ОКТЯБРЬ') && latestFin.profit < prevFin.profit) {
        insights.critical.push('Снижение прибыли в 2025 году может быть связано с ростом мировых цен на какао-бобы, что давит на маржинальность.');
    }

    if (insights.critical.length === 0) insights.critical.push('Значимых критических событий не выявлено.');
    if (insights.positive.length === 0) insights.positive.push('Явных точек роста в последнем периоде не обнаружено.');
    if (insights.warning.length === 0) insights.warning.push('Существенных зон для беспокойства не найдено.');

    return insights;
}

/**
 * =================================================================================
 * ИИ-АГЕНТ #4: Сравнительный анализ компаний ВНУТРИ ОДНОЙ ОТРАСЛИ.
 * Имитирует получение инсайтов для страницы отраслевого анализа.
 * Вместо промпта используется поиск по ключу отрасли в моковых данных.
 * @param companiesInIndustry - Массив данных по компаниям, принадлежащим к одной отрасли.
 * @returns Промис, который разрешается объектом с инсайтами по 4 категориям.
 * =================================================================================
 */
export async function fetchIndustrySpecificInsights(companiesInIndustry: CompanyData[]): Promise<{ [key in InsightType]: string[] }> {
    await new Promise(resolve => setTimeout(resolve, 900)); // Имитация задержки сети

    if (!companiesInIndustry || companiesInIndustry.length === 0) {
        return { critical: [], positive: [], warning: [], info: [] };
    }

    const industryName = companiesInIndustry[0].industry;
    const mockResponse = mockIndustrySpecificInsights[industryName];

    if (mockResponse) {
        // Если в моке есть пустые поля, заполняем их стандартными заглушками.
        const filledResponse = { ...mockResponse };
        (Object.keys(filledResponse) as InsightType[]).forEach(key => {
            if (filledResponse[key].length === 0) {
                 if (key === 'critical') filledResponse[key].push('Значимых критических событий не выявлено.');
                 if (key === 'positive') filledResponse[key].push('Явных точек роста в последнем периоде не обнаружено.');
                 if (key === 'warning') filledResponse[key].push('Существенных зон для беспокойства не найдено.');
                 if (key === 'info') filledResponse[key].push('Дополнительных интересных фактов не найдено.');
            }
        });
        return filledResponse;
    }
    
    // Заглушка, если для отрасли нет предопределенных инсайтов
    return {
        critical: ['Значимых критических событий не выявлено.'],
        positive: ['Явных точек роста в последнем периоде не обнаружено.'],
        warning: ['Существенных зон для беспокойства не найдено.'],
        info: [`В данной отрасли (${industryName}) для анализа представлена только одна компания.`]
    };
}