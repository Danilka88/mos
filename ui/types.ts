/**
 * @interface YearlyData
 * @description Описывает структуру финансовых и операционных показателей компании за один конкретный год.
 */
export interface YearlyData {
    year: number;                // Отчетный год
    revenue: number;             // Выручка, тыс. руб.
    profit: number;              // Чистая прибыль (или убыток), тыс. руб.
    employees: number;           // Среднесписочная численность персонала, чел.
    taxes: number;               // Общая сумма уплаченных налогов, тыс. руб.
    payroll: number;             // Фонд оплаты труда (ФОТ), тыс. руб.
    profitTax: number;           // Налог на прибыль, тыс. руб.
    propertyTax: number;         // Налог на имущество, тыс. руб.
    personalIncomeTax: number;   // НДФЛ, уплаченный за сотрудников, тыс. руб.
}

/**
 * @interface CompanyData
 * @description Описывает полную структуру данных по одной компании, включая ее общие реквизиты и массив годовых финансовых показателей.
 */
export interface CompanyData {
    id: number;                  // Уникальный идентификатор компании в рамках приложения
    name: string;                // Краткое наименование организации
    inn: string;                 // ИНН (Идентификационный номер налогоплательщика)
    industry: string;            // Отрасль промышленности (для агрегированного и сравнительного анализа)
    activityType: string;        // Основной вид деятельности (ОКВЭД, для будущего расширения аналитики)
    financials: YearlyData[];    // Массив финансовых показателей по годам
}

/**
 * @type InsightType
 * @description Определяет типы аналитических выводов (инсайтов), которые может генерировать ИИ.
 * Используется для стилизации карточек, фильтрации и формирования специфичных запросов к ИИ-агентам.
 */
export type InsightType = 'critical' | 'warning' | 'positive' | 'info';

/**
 * @type AnalysisMode
 * @description Определяет режим анализа на главном дашборде и странице "Все события": по отдельным компаниям или по отраслям в целом.
 */
export type AnalysisMode = 'company' | 'industry';